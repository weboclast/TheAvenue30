#!/usr/bin/env node
/*
 * Regenerates references/components.md from the installed @appica packages.
 *
 * The index is a build artifact, not a hand-maintained list: it reads the
 * subpath exports out of node_modules, so it always matches the version the
 * project actually has installed. Run it after `pnpm update '@appica/*'`.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const SKILL_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUTPUT = join(SKILL_DIR, 'references', 'components.md')

const HELP = `Usage: node scripts/sync-component-index.mjs [OPTIONS]

Regenerate the Appica UI component index from the installed packages.

Options:
  --check        Exit 1 if the index is stale, without writing. For CI.
  --output FILE  Write to FILE instead of references/components.md.
  --help         Show this message.

Exit codes:
  0  Index written, or already up to date under --check.
  1  Index is stale (--check only).
  2  A package could not be read. Run \`pnpm install\` first.
`

function parseArgs(argv) {
  const options = { check: false, output: OUTPUT }
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i]
    if (arg === '--help' || arg === '-h') return { help: true }
    else if (arg === '--check') options.check = true
    else if (arg === '--output') {
      options.output = argv[++i]
      if (!options.output) fail(`--output needs a file path.\n${HELP}`)
    } else fail(`Unknown option: "${arg}"\n${HELP}`)
  }
  return options
}

function fail(message, code = 2) {
  process.stderr.write(`Error: ${message}\n`)
  process.exit(code)
}

/**
 * Walks up from the skill directory to find a package in node_modules, so the
 * script works from any cwd and from a symlinked .claude/skills/ entry.
 */
function readPackage(name) {
  let dir = SKILL_DIR
  while (true) {
    try {
      return JSON.parse(readFileSync(join(dir, 'node_modules', name, 'package.json'), 'utf8'))
    } catch {
      const parent = dirname(dir)
      if (parent === dir) fail(`${name} is not installed. Run \`pnpm install\` from the project root.`)
      dir = parent
    }
  }
}

// Subpaths whose docs live on a parent page instead of one of their own. A
// `-group` variant is documented alongside the control it groups, and `./color`
// is a value type rather than a component. Everything else follows the pattern.
const DOCS_ALIASES = {
  './checkbox-group': 'components/react/checkbox',
  './radio-group': 'components/react/radio',
  './fieldset': 'components/react/field',
  './color': 'docs/react/colors',
}

/** Maps an export subpath to its documentation URL, which is always the `.md` form. */
function docsUrl(subpath) {
  const alias = DOCS_ALIASES[subpath]
  if (alias) return `https://appica.dev/ui/${alias}.md`

  const name = subpath.replace(/^\.\//, '')
  if (name.startsWith('hooks/')) return `https://appica.dev/ui/docs/react/${name.slice('hooks/'.length)}.md`
  if (name.startsWith('providers/')) return `https://appica.dev/ui/docs/react/${name.slice('providers/'.length)}.md`
  return `https://appica.dev/ui/components/react/${name}.md`
}

function render() {
  const ui = readPackage('@appica/ui-react')
  const icons = readPackage('@appica/icons-react')
  const flags = readPackage('@appica/country-flags-react')

  // `.`, `./package.json` and the stylesheets are not component entry points.
  const subpaths = Object.keys(ui.exports ?? {}).filter(
    (key) => key !== '.' && key !== './package.json' && !key.endsWith('.css') && key !== './css',
  )
  const components = subpaths.filter((key) => !key.startsWith('./hooks/') && !key.startsWith('./providers/'))
  const hooks = subpaths.filter((key) => key.startsWith('./hooks/'))
  const providers = subpaths.filter((key) => key.startsWith('./providers/'))

  const table = (entries) =>
    [
      '| Import from | Docs |',
      '| --- | --- |',
      ...entries.map((key) => `| \`@appica/ui-react${key.slice(1)}\` | ${docsUrl(key)} |`),
    ].join('\n')

  return `<!-- Generated by scripts/sync-component-index.mjs. Do not edit by hand. -->

# Appica UI component index

Every entry point in \`@appica/ui-react@${ui.version}\`, as installed. If a
component you want is on this list, import it. If it is not, it does not exist
in this version, so compose one from what is here.

Fetch the docs URL before using a component for the first time. Each one is
clean markdown, roughly 8 KB, covering props and examples.

## Components (${components.length})

${table(components)}

## Hooks (${hooks.length})

${table(hooks)}

## Providers (${providers.length})

${table(providers)}

## Icons and flags

| Package | Version | Import from | Docs |
| --- | --- | --- | --- |
| \`@appica/icons-react\` | ${icons.version} | package root | https://appica.dev/ui/icons.md |
| \`@appica/country-flags-react\` | ${flags.version} | package root | https://appica.dev/ui/country-flags.md |

Icons and flags are the exception to the subpath rule: both are imported from
the package root, one named export per icon.

\`\`\`tsx
import { ShoppingCart } from '@appica/icons-react'
import { US } from '@appica/country-flags-react'
\`\`\`
`
}

const options = parseArgs(process.argv.slice(2))
if (options.help) {
  process.stdout.write(HELP)
  process.exit(0)
}

const next = render()

if (options.check) {
  let current = ''
  try {
    current = readFileSync(options.output, 'utf8')
  } catch {
    /* Missing counts as stale. */
  }
  if (current === next) {
    process.stderr.write('Component index is up to date.\n')
    process.exit(0)
  }
  process.stderr.write(
    `Component index is stale: ${options.output}\nRun \`node scripts/sync-component-index.mjs\` to regenerate it.\n`,
  )
  process.exit(1)
}

writeFileSync(options.output, next)
process.stderr.write(`Wrote ${options.output}\n`)
