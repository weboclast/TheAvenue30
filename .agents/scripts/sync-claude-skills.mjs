#!/usr/bin/env node
/*
 * Generates the `.claude/skills/` pointer files from `.agents/skills/`.
 *
 * Skills live once, in `.agents/skills/`, in the open Agent Skills format.
 * Claude Code only discovers skills under `.claude/skills/`, and offers no
 * setting to look elsewhere, so it needs an entry of its own for each one. A
 * symlink would do it on macOS and Linux, but not in a zip a Windows buyer
 * extracts, so each entry is a real file holding the skill's frontmatter and a
 * line telling the agent where the instructions are.
 *
 * The frontmatter is copied verbatim, so the two copies of a description cannot
 * drift in wording. `--check` fails when they have drifted anyway, and runs as
 * part of `pnpm verify`. Both modes also refuse a `name` or `description` that
 * breaks the Agent Skills rules, which agents enforce by skipping the skill.
 *
 * Deleting `.claude/` entirely is a supported choice: the check treats a missing
 * directory as "this project doesn't use Claude Code" and passes.
 */

import { mkdirSync, readdirSync, readFileSync, rmSync, existsSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const SOURCE = join(ROOT, '.agents', 'skills')
const TARGET = join(ROOT, '.claude', 'skills')

const HELP = `Usage: node .agents/scripts/sync-claude-skills.mjs [OPTIONS]

Regenerate .claude/skills/ pointer files from the skills in .agents/skills/.
Run it after adding, renaming, or removing a skill, or after editing a skill's
description.

Options:
  --check   Exit 1 if the pointers are out of date, without writing. For CI.
  --help    Show this message.

Exit codes:
  0  Pointers written, already current under --check, or .claude/ is absent.
  1  Pointers are out of date (--check only).
  2  A skill could not be read, or its name or description breaks the rules.
`

function fail(message) {
  process.stderr.write(`Error: ${message}\n`)
  process.exit(2)
}

/**
 * Pulls the `name` and `description` keys out of a SKILL.md's frontmatter as raw
 * text. Copying the lines rather than parsing and re-serializing the YAML keeps
 * block scalars (`description: >-`) byte-identical in both copies.
 */
function readFrontmatter(skillPath) {
  const source = readFileSync(skillPath, 'utf8')
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---/)
  if (!match) fail(`${skillPath} has no YAML frontmatter.`)

  const kept = []
  let keeping = false
  for (const line of match[1].split(/\r?\n/)) {
    // A top-level key starts at column 0; anything indented continues the one above.
    if (/^[A-Za-z_][\w-]*:/.test(line)) keeping = /^(name|description):/.test(line)
    if (keeping) kept.push(line)
  }

  if (!kept.some((line) => line.startsWith('name:'))) fail(`${skillPath} has no \`name\` in its frontmatter.`)
  if (!kept.some((line) => line.startsWith('description:'))) {
    fail(`${skillPath} has no \`description\` in its frontmatter. Claude Code needs one to know when to load it.`)
  }
  return kept.join('\n')
}

/** A frontmatter key's text, with its continuation lines folded into 1 and its quotes or block indicator dropped. */
function readValue(frontmatter, key) {
  const lines = frontmatter.split(/\r?\n/)
  const at = lines.findIndex((line) => line.startsWith(`${key}:`))
  const continued = []
  for (const line of lines.slice(at + 1)) {
    if (!/^\s/.test(line)) break
    continued.push(line.trim())
  }
  const inline = lines[at].slice(key.length + 1).trim()
  const head = /^[>|][+-]?$/.test(inline) ? [] : [inline]
  return [...head, ...continued]
    .join(' ')
    .trim()
    .replace(/^(['"])([\s\S]*)\1$/, '$2')
}

/** Fails on the Agent Skills rules a skill breaks, since an agent that enforces one skips the skill without a word. */
function validate(skill, frontmatter) {
  const where = `.agents/skills/${skill}/SKILL.md`
  const name = readValue(frontmatter, 'name')
  if (name !== skill) fail(`${where} is named "${name}", and a skill's name has to match its folder.`)
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name) || name.length > 64) {
    fail(`${where}: a name is lowercase letters, digits, and single hyphens, up to 64 characters.`)
  }
  if (/anthropic|claude/.test(name)) fail(`${where}: "anthropic" and "claude" are reserved in a skill's name.`)

  const description = readValue(frontmatter, 'description')
  if (description.length > 1024) {
    fail(`${where}: the description runs to ${description.length} characters, and the limit is 1024.`)
  }
  if (/<\/?[a-z][^>]*>/i.test(description)) fail(`${where}: a description cannot hold XML tags.`)
}

function render(skill, frontmatter) {
  return `---
${frontmatter}
---

<!-- Generated by .agents/scripts/sync-claude-skills.mjs. Edit the source skill, not this file. -->

Read [.agents/skills/${skill}/SKILL.md](../../../.agents/skills/${skill}/SKILL.md)
and follow it. That file is this skill; every path it mentions is relative to
\`.agents/skills/${skill}/\`.
`
}

const argv = process.argv.slice(2)
if (argv.includes('--help') || argv.includes('-h')) {
  process.stdout.write(HELP)
  process.exit(0)
}
const check = argv.includes('--check')
for (const arg of argv) {
  if (arg !== '--check') fail(`Unknown option: "${arg}"\n${HELP}`)
}

if (!existsSync(TARGET) && check) {
  process.stderr.write('No .claude/skills/ directory, nothing to check.\n')
  process.exit(0)
}

const skills = readdirSync(SOURCE, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && existsSync(join(SOURCE, entry.name, 'SKILL.md')))
  .map((entry) => entry.name)
  .sort()

const expected = new Map(
  skills.map((skill) => {
    const frontmatter = readFrontmatter(join(SOURCE, skill, 'SKILL.md'))
    validate(skill, frontmatter)
    return [skill, render(skill, frontmatter)]
  }),
)
const existing = existsSync(TARGET)
  ? readdirSync(TARGET, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
  : []

const stale = []
for (const [skill, contents] of expected) {
  let current = null
  try {
    current = readFileSync(join(TARGET, skill, 'SKILL.md'), 'utf8')
  } catch {
    /* Missing counts as stale. */
  }
  if (current !== contents) stale.push(skill)
}
const orphaned = existing.filter((skill) => !expected.has(skill))

if (check) {
  if (stale.length === 0 && orphaned.length === 0) {
    process.stderr.write(`Claude Code skill pointers are up to date (${expected.size}).\n`)
    process.exit(0)
  }
  if (stale.length > 0) process.stderr.write(`Out of date: ${stale.join(', ')}\n`)
  if (orphaned.length > 0) process.stderr.write(`No longer in .agents/skills/: ${orphaned.join(', ')}\n`)
  process.stderr.write('Run `node .agents/scripts/sync-claude-skills.mjs` to regenerate them.\n')
  process.exit(1)
}

for (const [skill, contents] of expected) {
  mkdirSync(join(TARGET, skill), { recursive: true })
  writeFileSync(join(TARGET, skill, 'SKILL.md'), contents)
}
for (const skill of orphaned) {
  rmSync(join(TARGET, skill), { recursive: true, force: true })
}

const summary = [`${expected.size} pointer${expected.size === 1 ? '' : 's'} written`]
if (orphaned.length > 0) summary.push(`${orphaned.length} removed`)
process.stderr.write(`${summary.join(', ')} in .claude/skills/\n`)
