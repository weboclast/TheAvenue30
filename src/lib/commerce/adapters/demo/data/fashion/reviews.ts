import type { ProductReview, ProductReviewMedia } from '@/lib/commerce/types'

/*
 * Customer reviews for the Fashion demo, keyed by product slug. A product left
 * out has none, which is the state most of the catalog is in: its page drops
 * the reviews section.
 *
 * Each review answers the store's fit question (`fit`, -2 to 2) against the
 * size it was bought in, which is what the fit scale and the sizing advice are
 * averaged from. Topics use one small vocabulary per product, so they group.
 *
 * Photography lives under `/public/demo/fashion/reviews/<slug>/`, numbered, and
 * is assigned to a review here because a filename can't say who took it.
 */

/** Every review photo in this demo is a phone shot cropped to 3:4. */
const SHOT = { width: 768, height: 1024 }

/** One numbered shot from a product's review folder. */
function photo(slug: string, index: number, alt: string): ProductReviewMedia {
  return { kind: 'image', src: `/demo/fashion/reviews/${slug}/${index}.webp`, alt, ...SHOT }
}

